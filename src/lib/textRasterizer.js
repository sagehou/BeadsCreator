const FALLBACK_GLYPH = ['#####', '#...#', '#.#.#', '#...#', '#.#.#', '#...#', '#####'];

function scaleRows(rows, size) {
  if (size <= 1) return rows.map((row) => [...row]);

  const scaled = [];
  for (const row of rows) {
    const expandedRow = [...row].flatMap((value) => Array(size).fill(value));
    for (let i = 0; i < size; i += 1) scaled.push([...expandedRow]);
  }
  return scaled;
}

function glyphForCharacter(character) {
  const glyph = FONT_5X7[character.toUpperCase()] ?? FALLBACK_GLYPH;
  return glyph.map((row) => [...row].map((value) => (value === '#' ? '#' : '.')));
}

export function rasterizeTextToGrid(text, options = {}) {
  const size = Math.max(1, Math.floor(Number(options.size ?? 1)));
  const spacing = Math.max(0, Math.floor(Number(options.letterSpacing ?? 1))) * size;
  const characters = [...(text || ' ')];
  const glyphRows = Array.from({ length: 7 }, () => []);

  characters.forEach((character, index) => {
    const glyph = glyphForCharacter(character);
    for (let y = 0; y < glyph.length; y += 1) {
      glyphRows[y].push(...glyph[y]);
      if (index < characters.length - 1) glyphRows[y].push(...Array(spacing).fill('.'));
    }
  });

  return scaleRows(glyphRows, size);
}

export function stampTextOnGrid(grid, text, options = {}) {
  const nextGrid = grid.map((row) => [...row]);
  const mask = rasterizeTextToGrid(text, options);
  const originX = Math.floor(Number(options.x ?? 0));
  const originY = Math.floor(Number(options.y ?? 0));
  const color = options.color ?? '#000000';

  for (let y = 0; y < mask.length; y += 1) {
    for (let x = 0; x < (mask[y]?.length ?? 0); x += 1) {
      if (mask[y][x] !== '#') continue;
      const targetY = originY + y;
      const targetX = originX + x;
      if (targetY < 0 || targetX < 0 || targetY >= nextGrid.length || targetX >= (nextGrid[0]?.length ?? 0)) continue;
      nextGrid[targetY][targetX] = color;
    }
  }

  return nextGrid;
}
