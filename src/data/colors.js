/**
 * Find the closest palette color to a given RGB using Euclidean distance
 */
export function findClosestColor(r, g, b, palette) {
  let minDist = Infinity;
  let closest = palette[0];
  
  for (const color of palette) {
    const cr = parseInt(color.hex.slice(1, 3), 16);
    const cg = parseInt(color.hex.slice(3, 5), 16);
    const cb = parseInt(color.hex.slice(5, 7), 16);
    const dist = (r - cr) ** 2 + (g - cg) ** 2 + (b - cb) ** 2;
    if (dist < minDist) {
      minDist = dist;
      closest = color;
    }
  }
  return closest;
}

/**
 * Convert hex to RGB
 */
export function hexToRgb(hex) {
  const r = parseInt(hex.slice(1, 3), 16);
  const g = parseInt(hex.slice(3, 5), 16);
  const b = parseInt(hex.slice(5, 7), 16);
  return { r, g, b };
}

/**
 * Generate the default smiley face pattern for 29x29 grid
 */
export function generateSmileyPattern() {
  const size = 29;
  const grid = Array.from({ length: size }, () => Array(size).fill(null));
  const cx = 14, cy = 14;
  
  // Yellow face circle
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      const dist = Math.sqrt((x - cx) ** 2 + (y - cy) ** 2);
      if (dist <= 12) {
        grid[y][x] = '#FFD700'; // Yellow
      }
    }
  }
  
  // Black border circle
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      const dist = Math.sqrt((x - cx) ** 2 + (y - cy) ** 2);
      if (dist >= 11.5 && dist <= 13) {
        grid[y][x] = '#1A1A1A'; // Black
      }
    }
  }
  
  // Left eye
  for (let dy = -3; dy <= -1; dy++) {
    for (let dx = -4; dx <= -3; dx++) {
      grid[cy + dy][cx + dx] = '#1A1A1A';
    }
  }
  
  // Right eye
  for (let dy = -3; dy <= -1; dy++) {
    for (let dx = 3; dx <= 4; dx++) {
      grid[cy + dy][cx + dx] = '#1A1A1A';
    }
  }
  
  // Smile mouth - arc
  for (let x = -5; x <= 5; x++) {
    const yOff = Math.round(0.15 * x * x) + 3;
    if (yOff <= 7) {
      grid[cy + yOff][cx + x] = '#DC143C'; // Red
      if (yOff + 1 <= 8 && cy + yOff + 1 < size) {
        grid[cy + yOff + 1][cx + x] = '#DC143C';
      }
    }
  }
  
  // Cheek blush - left
  for (let dy = 1; dy <= 3; dy++) {
    for (let dx = -8; dx <= -6; dx++) {
      if (cx + dx >= 0 && cy + dy < size) {
        const dist = Math.sqrt((cx + dx - cx) ** 2 + (cy + dy - cy) ** 2);
        if (dist <= 12) {
          grid[cy + dy][cx + dx] = '#FF69B4';
        }
      }
    }
  }
  
  // Cheek blush - right  
  for (let dy = 1; dy <= 3; dy++) {
    for (let dx = 6; dx <= 8; dx++) {
      if (cx + dx < size && cy + dy < size) {
        const dist = Math.sqrt((cx + dx - cx) ** 2 + (cy + dy - cy) ** 2);
        if (dist <= 12) {
          grid[cy + dy][cx + dx] = '#FF69B4';
        }
      }
    }
  }
  
  return grid;
}
